#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
APP_NAME="WebMux"
BUNDLE="$SCRIPT_DIR/$APP_NAME.app"
BUILD_DIR="$SCRIPT_DIR/.build"
INSTALL_DIR="/Applications"

# --- Helpers ---
info()  { printf "\033[1;34m==>\033[0m %s\n" "$1"; }
ok()    { printf "\033[1;32m==>\033[0m %s\n" "$1"; }
fail()  { printf "\033[1;31m==>\033[0m %s\n" "$1" >&2; exit 1; }

# --- SDK selection ---
# Newer SDKs (e.g. macOS 27) declare SwiftUI's @State as a macro whose plugin
# (SwiftUIMacros) ships only with Xcode. With Command Line Tools alone, the
# default SDK may therefore fail to compile. Probe the default SDK first and
# fall back to the newest installed SDK that works. An explicit SDKROOT wins.

# Returns 0 if the given SDK (or the default one, if empty) can compile @State.
sdk_supports_swiftui() {
    local sdk="$1"
    local probe_dir
    probe_dir="$(mktemp -d)"
    cat > "$probe_dir/probe.swift" << 'SWIFT'
import SwiftUI
struct Probe: View {
    @State private var n = 0
    var body: some View { Text("\(n)") }
}
SWIFT
    local args=(-typecheck -target "$(uname -m)-apple-macos14.0" "$probe_dir/probe.swift")
    [[ -n "$sdk" ]] && args+=(-sdk "$sdk")
    local rc=0
    swiftc "${args[@]}" > /dev/null 2>&1 || rc=$?
    rm -rf "$probe_dir"
    return "$rc"
}

select_sdk() {
    if [[ -n "${SDKROOT:-}" ]]; then
        info "Using SDK from environment: $SDKROOT"
        return
    fi
    if sdk_supports_swiftui ""; then
        return  # default SDK works, nothing to do
    fi

    local dev_dir sdk
    dev_dir="$(xcode-select -p)"
    while IFS= read -r sdk; do
        [[ -L "$sdk" ]] && continue  # skip aliases like MacOSX.sdk
        if sdk_supports_swiftui "$sdk"; then
            export SDKROOT="$sdk"
            info "Default SDK can't compile SwiftUI here; using $(basename "$sdk")"
            return
        fi
    done < <(ls -d "$dev_dir"/SDKs/MacOSX*.sdk \
                   "$dev_dir"/Platforms/MacOSX.platform/Developer/SDKs/MacOSX*.sdk 2>/dev/null | sort -rV)

    fail "No installed macOS SDK can compile SwiftUI. Install Xcode, or set SDKROOT to a working SDK."
}

usage() {
    cat <<EOF
Usage: $(basename "$0") [command]

Commands:
  build       Build debug binary (default)
  release     Build optimized release binary
  run         Build and launch the app
  install     Build release and copy to /Applications
  clean       Remove build artifacts
  bundle      Build and create .app bundle (without installing)
EOF
    exit 0
}

# --- Commands ---
do_build() {
    local mode="${1:-debug}"

    # Generate BuildInfo.swift before compiling
    local git_version
    git_version="$(git -C "$SCRIPT_DIR" describe --tags --always 2>/dev/null || echo "dev")"
    local build_date
    build_date="$(date '+%Y-%m-%d')"
    cat > "$SCRIPT_DIR/Sources/WebMux/BuildInfo.swift" << SWIFT
// Auto-generated by build.sh — do not edit
enum BuildInfo {
    static let version = "$git_version"
    static let buildDate = "$build_date"
}
SWIFT

    select_sdk

    # When building against a non-default SDK, the linker otherwise stamps the
    # binary with the deployment target (14.0) as its SDK version, which makes
    # AppKit/SwiftUI fall back to old macOS 14 compatibility behaviour.
    local link_flags=()
    if [[ -n "${SDKROOT:-}" ]]; then
        local sdk_version
        sdk_version="$(plutil -extract Version raw "$SDKROOT/SDKSettings.json" 2>/dev/null || true)"
        if [[ -n "$sdk_version" ]]; then
            link_flags=(-Xlinker -platform_version -Xlinker macos -Xlinker 14.0 -Xlinker "$sdk_version")
        fi
    fi

    info "Building ($mode)..."
    if [[ "$mode" == "release" ]]; then
        swift build -v -c release --package-path "$SCRIPT_DIR" ${link_flags[@]+"${link_flags[@]}"}
    else
        swift build -v --package-path "$SCRIPT_DIR" ${link_flags[@]+"${link_flags[@]}"}
    fi
    ok "Build complete"
}

do_bundle() {
    local mode="${1:-debug}"
    do_build "$mode"

    info "Creating app bundle..."
    rm -rf "$BUNDLE"
    mkdir -p "$BUNDLE/Contents/MacOS"

    local bin="$BUILD_DIR/arm64-apple-macosx/$mode/$APP_NAME"
    [[ -f "$bin" ]] || bin="$BUILD_DIR/$mode/$APP_NAME"
    [[ -f "$bin" ]] || fail "Binary not found after build"

    cp "$bin" "$BUNDLE/Contents/MacOS/$APP_NAME"

    # Copy icon if present
    mkdir -p "$BUNDLE/Contents/Resources"
    if [[ -f "$SCRIPT_DIR/AppIcon.icns" ]]; then
        cp "$SCRIPT_DIR/AppIcon.icns" "$BUNDLE/Contents/Resources/AppIcon.icns"
    fi

    # Generate version from git
    local git_version
    git_version="$(git -C "$SCRIPT_DIR" describe --tags --always 2>/dev/null || echo "dev")"
    local build_date
    build_date="$(date '+%Y-%m-%d')"

    cat > "$BUNDLE/Contents/Info.plist" << PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
    <key>CFBundleExecutable</key>
    <string>WebMux</string>
    <key>CFBundleIdentifier</key>
    <string>com.webmux.app</string>
    <key>CFBundleName</key>
    <string>WebMux</string>
    <key>CFBundlePackageType</key>
    <string>APPL</string>
    <key>CFBundleVersion</key>
    <string>$git_version</string>
    <key>CFBundleShortVersionString</key>
    <string>$git_version</string>
    <key>CFBundleIconFile</key>
    <string>AppIcon</string>
    <key>LSMinimumSystemVersion</key>
    <string>14.0</string>
    <key>NSAppTransportSecurity</key>
    <dict>
        <key>NSAllowsArbitraryLoads</key>
        <true/>
    </dict>
    <key>NSHumanReadableCopyright</key>
    <string>MIT License</string>
</dict>
</plist>
PLIST

    # Sign with stable identity to avoid keychain prompts on rebuild
    codesign --force --deep --sign "WebMux Dev" --entitlements "$SCRIPT_DIR/WebMux.entitlements" "$BUNDLE"

    ok "Bundle created at $BUNDLE"
}

do_run() {
    pkill -f "$APP_NAME.app/Contents/MacOS/$APP_NAME" 2>/dev/null || true
    sleep 0.5
    do_bundle debug
    info "Launching $APP_NAME..."
    open "$BUNDLE"
}

do_install() {
    do_bundle release
    info "Installing to $INSTALL_DIR..."
    pkill -f "$APP_NAME.app/Contents/MacOS/$APP_NAME" 2>/dev/null || true
    sleep 1
    rm -rf "$INSTALL_DIR/$APP_NAME.app"
    cp -R "$BUNDLE" "$INSTALL_DIR/$APP_NAME.app"
    ok "Installed to $INSTALL_DIR/$APP_NAME.app"
    open "$INSTALL_DIR/$APP_NAME.app"
}

do_clean() {
    info "Cleaning..."
    rm -rf "$BUILD_DIR" "$BUNDLE"
    ok "Clean complete"
}

# --- Main ---
case "${1:-build}" in
    build)   do_build debug ;;
    release) do_build release ;;
    run)     do_run ;;
    install) do_install ;;
    clean)   do_clean ;;
    bundle)  do_bundle debug ;;
    help|-h|--help) usage ;;
    *) fail "Unknown command: $1. Run with 'help' for usage." ;;
esac
